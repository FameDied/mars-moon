flat_missions = []
for m in missions:
    item = dict(m)
    item["payload_json"] = json.dumps(item.pop("payload", []))
    flat_missions.append(item)

flat_sites = []
for s in surface_sites:
    item = dict(s)
    item["hardware_inventory_json"] = json.dumps(item.pop("hardware_inventory", []))
    flat_sites.append(item)

# Save Missions
with open("data/processed/json/missions_catalog.json", "w", encoding="utf-8") as f:
    json.dump(missions, f, indent=2)
